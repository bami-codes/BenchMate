def caption_png(text, path):
    img = Image.new('RGBA', (W, 170), (0, 0, 0, 0)); d = ImageDraw.Draw(img)
    font = ImageFont.truetype(FONT_N, 44)
    try: font.set_variation_by_name('SemiBold')
    except Exception: pass
    # wrap to two lines max
    words, lines, cur = text.split(), [], ''
    for w_ in words:
        t = (cur + ' ' + w_).strip()
        if d.textlength(t, font=font) > W - 260 and cur: lines.append(cur); cur = w_
        else: cur = t
    if cur: lines.append(cur)
    lh = 54; y = 170 - 22 - lh * len(lines)
    for ln in lines:
        tw = d.textlength(ln, font=font); x = (W - tw) / 2
        d.rounded_rectangle([x - 18, y - 4, x + tw + 18, y + lh - 2], radius=8, fill=(14, 19, 21, 215))
        d.text((x, y), ln, font=font, fill=(251, 251, 248, 255)); y += lh
    img.save(path)


def bed(total_s, path):
    """A quiet pad: slow chords, low-passed by a moving average; -24 dBFS peak."""
    sr = 48000; n = int(total_s * sr); t = np.arange(n) / sr
    chords = [[57, 60, 64, 67], [53, 57, 60, 64], [48, 55, 60, 64], [55, 59, 62, 67]]; bar = 8.0
    out = np.zeros(n, dtype=np.float32); rng = np.random.default_rng(3)
    for bi in range(int(math.ceil(total_s / bar))):
        s0, s1 = int(bi * bar * sr), min(n, int((bi + 1) * bar * sr) + sr)
        tt = np.arange(s1 - s0) / sr; env = np.minimum(1, tt / 1.5) * np.minimum(1, np.maximum(0, (bar + 1 - tt)) / 1.5)
        seg = np.zeros(s1 - s0, dtype=np.float32)
        for m in chords[bi % 4]:
            for det in (-0.06, 0.06):
                f = 440 * 2 ** ((m + det - 69) / 12); ph = rng.uniform(0, 2 * np.pi)
                seg += (np.sin(2 * np.pi * f * tt + ph) + 0.18 * np.sin(4 * np.pi * f * tt + ph)).astype(np.float32)
        out[s0:s1] += seg * env / 8
    k = 96; out = np.convolve(out, np.ones(k) / k, mode='same')
    fade = int(2.5 * sr); out[:fade] *= np.linspace(0, 1, fade); out[-fade:] *= np.linspace(1, 0, fade)
    out = out / (np.abs(out).max() + 1e-9) * 10 ** (-24 / 20)
    with wave.open(str(path), 'wb') as w:
        w.setnchannels(1); w.setsampwidth(2); w.setframerate(sr); w.writeframes((out * 32767).astype(np.int16).tobytes())


def main():
    cues = json.loads((RAW / 'cues.json').read_text())
    OUT.mkdir(exist_ok=True); CAP.mkdir(exist_ok=True)
    order = ['s1-landing', 's2-case01', 's3-case04', 's4-case05', 's5-case02', 's6-bench', 's7-verify', 's8-close']
    caps = captions_for(cues)
    # scene timeline; trims: each replay scene is cut at its verdict hold; the landing/bench scenes as recorded
    parts, t_acc, srt, n = [], 0.0, [], 1
    filters, inputs = [], []
    for i, s in enumerate(order):
        meta = cues[s]; dur = meta['duration']
        trim_end = min(dur, {'s1-landing': 9.8, 's6-bench': 11.4, 's7-verify': 11.8, 's8-close': 6.2}.get(s, dur))
        if 'Verdict · compared by code' in meta['cues']:
            trim_end = min(dur, meta['cues']['Verdict · compared by code'] + 4.2)
        parts.append((s, meta['file'], trim_end))
        for j, (st, d, text) in enumerate(sorted(caps.get(s, []), key=lambda x: x[0])):
            if st >= trim_end: continue
            en = min(trim_end - 0.1, st + (d or 3.5))
            png = CAP / f'{s}-{j}.png'; caption_png(text, png)
            inputs.append(png); filters.append((len(inputs), t_acc + st, t_acc + en))
            a, b = t_acc + st, t_acc + en
            srt.append(f"{n}\n{fmt(a)} --> {fmt(b)}\n{text}\n"); n += 1
        t_acc += trim_end
    total = t_acc
    print('scenes', [(s, round(e, 1)) for s, _, e in parts], 'total', round(total, 1), 's')
    assert total <= MAX_S + 2, f'too long: {total:.1f}s'
    bed(total + 1, OUT / 'bed.wav')
    # concat with trims
    cmd = ['ffmpeg', '-y', '-loglevel', 'error']
    for s, f, e in parts: cmd += ['-t', f'{e:.3f}', '-i', f]
    for png in inputs: cmd += ['-loop', '1', '-i', str(png)]
    cmd += ['-i', str(OUT / 'bed.wav')]
    nv = len(parts); fc = []
    for i in range(nv): fc.append(f'[{i}:v]scale={W}:{H}:force_original_aspect_ratio=decrease,pad={W}:{H}:(ow-iw)/2:(oh-ih)/2,setsar=1,fps={FPS},format=yuv420p[v{i}]')
    fc.append(''.join(f'[v{i}]' for i in range(nv)) + f'concat=n={nv}:v=1:a=0[base]')
    last = 'base'
    for k, (idx, a, b) in enumerate(filters):
        fc.append(f'[{last}][{nv + idx - 1}:v]overlay=0:{H - 170}:enable=\'between(t,{a:.3f},{b:.3f})\'[o{k}]'); last = f'o{k}'
    fc.append(f'[{last}]trim=0:{total:.3f},setpts=PTS-STARTPTS[vout]')
    cmd += ['-filter_complex', ';'.join(fc), '-map', '[vout]', '-map', f'{nv + len(inputs)}:a', '-c:v', 'libx264', '-preset', 'medium', '-crf', '19', '-r', str(FPS), '-c:a', 'aac', '-b:a', '128k', '-shortest', '-movflags', '+faststart', str(OUT / 'benchmate-demo.mp4')]
    subprocess.run(cmd, check=True)
    (OUT / 'benchmate-demo.srt').write_text('\n'.join(srt))
    probe = subprocess.run(['ffprobe', '-v', 'error', '-show_entries', 'format=duration', '-of', 'csv=p=0', str(OUT / 'benchmate-demo.mp4')], capture_output=True, text=True).stdout.strip()
    print('wrote', OUT / 'benchmate-demo.mp4', probe, 's')


def fmt(s):
    ms = int(round((s - int(s)) * 1000)); s = int(s)
    return f'{s // 3600:02d}:{s % 3600 // 60:02d}:{s % 60:02d},{ms:03d}'


if __name__ == '__main__':
    main()
