ROOT = V.parent
RAW, OUT, CAP = V / 'raw', V / 'out', V / 'captions'
FONT_N = os.environ.get('BM_FONT_NARROW', str(V / 'fonts' / 'ArchivoNarrow-var.ttf'))  # OFL, see fonts/archivo-OFL.txt
FONT = os.environ.get('BM_FONT', str(V / 'fonts' / 'Archivo-var.ttf'))
W, H, FPS = 1920, 1080, 30
MAX_S = 178.0


def run_json(rid):
    return json.loads((ROOT / 'site' / 'data' / 'runs' / f'{rid}.json').read_text())


