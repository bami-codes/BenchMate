"""Assemble the three-minute demo from the scene recordings: captions timed by the recorded cues, a quiet
synthesized bed (no third-party audio), one 1920×1080 H.264 MP4 with AAC, plus a matching .srt.

  node record_site.js            # raw/*.webm + raw/cues.json (the site filmed in real time)
  python3 assemble.py            # out/benchmate-demo.mp4, out/benchmate-demo.srt

Captions say what is on screen; every figure in them is read from the recorded runs (site/data/runs) at build time.
Nothing is generated by a model here: no synthetic imagery, no voice; the bed is a few sine-wave chords.
"""
import json, math, os, pathlib, subprocess, wave
import numpy as np
from PIL import Image, ImageDraw, ImageFont

