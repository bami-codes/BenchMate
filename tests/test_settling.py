"""Periodic-state regressions against analytic RC and independent ODE truth."""
import shutil
import numpy as np
import pytest
from scipy.integrate import solve_ivp
from scipy.optimize import brentq
from scipy.special import lambertw
from benchmate.physics import Acquisition,RCModel,predict
from benchmate.stimulus import command_template,commanded_waveform
from benchmate.netlist import simulate_netlist,topology_fingerprint
from benchmate.noise import adequacy
from benchmate.discovery import TRAINING,VERIFICATION,fit_proposal

pytestmark=pytest.mark.skipif(shutil.which('ngspice') is None,reason='ngspice not installed')


def rc_proposal(diode=False):
    result=[dict(name='R1',kind='R',a='IN',b='OUT',value=10000.,model='none'),
            dict(name='C1',kind='C',a='OUT',b='REF',value=1e-6,model='none')]
    if diode:result.append(dict(name='D1',kind='D',a='OUT',b='REF',value=0,model='generic_diode'))
    return result


@pytest.mark.parametrize('frequency',[1.,3.7])
def test_periodic_warmup_matches_analytic_rc_even_off_integer_grid(frequency):
    s=Acquisition(kind='sine',frequency_hz=frequency,amplitude_v=1,duration_s=1,sample_period_s=.002)
    invocations=[]
    p,m=simulate_netlist(rc_proposal(),command_template(s),before_run=lambda:invocations.append(1))
    expected=predict(RCModel(10000,1e-6),s)
    # 50 uV waveform accuracy (1/60 of development sigma) is distinct from
    # the 10 uV change tolerated when doubling the numerical pre-roll.
    np.testing.assert_allclose(p['out_v'],expected['out_v'],atol=5e-5,rtol=0)
    assert abs(p['out_v'][0]-s.ref_v)>.01  # DC startup would be REF.
    assert m['initial_state']['converged']
    assert m['initial_state']['max_node_difference_v']<=1e-5
    assert len(invocations)==len(m['simulator_invocations'])>=2
    assert m['topology_sha256']==topology_fingerprint(rc_proposal())


def test_unsettled_or_unsupported_input_cannot_silently_pass(monkeypatch):
    import benchmate.netlist as netlist
    s=Acquisition(kind='sine',frequency_hz=1)
    monkeypatch.setattr(netlist,'MAX_WARMUP_SECONDS',.05)
    with pytest.raises(ValueError,match='settling exceeds'):simulate_netlist(rc_proposal(),command_template(s))
    template=command_template(s);template['data']['drive_v'][4]+=.01
    with pytest.raises(ValueError,match='ideal command'):simulate_netlist(rc_proposal(),template)


def ode_capture(s):
    """Independent Shockley+RS ODE; warm-up is not generated by ngspice."""
    d=commanded_waveform(s);u=np.asarray(d['drive_v'])-d['ref_v'];t=np.asarray(d['time_s'])
    nv=1.9*8.617333262145e-5*300.15;isat=3e-9;gl=0 if s.load_ohm is None else 1/s.load_ohm
    def slope(v,vin):
        current=float(nv*lambertw(isat/nv*np.exp((v+isat)/nv)).real-isat)
        return ((vin-v)/10000-gl*v-current)/1e-6
    def advance(v,vin,dt):
        return float(solve_ivp(lambda t,y:[slope(y[0],vin)],(0,dt),[v],method='DOP853',rtol=1e-9,atol=1e-11).y[0,-1])
    if s.kind=='sine':
        v=0.;n=int(np.ceil(2/s.frequency_hz/s.sample_period_s))
        for k in range(-n,0):v=advance(v,s.amplitude_v*np.sin(2*np.pi*s.frequency_hz*k*s.sample_period_s),s.sample_period_s)
    else:v=brentq(lambda v:slope(v,u[0]),min(0,u[0])-.001,max(0,u[0])+.001)
    out=[v]
    for i,dt in enumerate(np.diff(t),1):out.append(advance(out[-1],u[i-1],dt))
    d.update(in_v=d['drive_v'],out_v=(np.asarray(d['ref_v'])+out).tolist())
    return {'source':'synthetic','settings':s.to_dict(),'data':d}


def test_capacitive_nonlinear_proposal_fits_and_predicts_independent_ode():
    training=[ode_capture(s) for s in TRAINING]
    fitted,result=fit_proposal(rc_proposal(True),training)
    assert result['training_passed'] and result['parameters_identifiable']
    assert result['simulator_calls']<=420 and result['simulation_cache_hits']>0
    assert fitted[1]['value']==pytest.approx(1e-6,rel=.01)
    for s in VERIFICATION:
        p,m=simulate_netlist(fitted,command_template(s),diode=result['diode_parameters'])
        assert adequacy(p,ode_capture(s))['passed']
    assert result['generated_topology_sha256']==result['fitted_topology_sha256']
